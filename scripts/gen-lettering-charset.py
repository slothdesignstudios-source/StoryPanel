#!/usr/bin/env python3
"""Writes apps/web/src/lib/lettering-charset.ts from the bundled fonts' character maps, so the browser
checks exactly what the server checks (tests/test_print_safe_area.py verifies the file is current)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services/backend/src"))
from storypanel.pipeline.lettering import SUPPORTED_SUMMARY, _supported  # noqa: E402

OUT = ROOT / "apps/web/src/lib/lettering-charset.ts"


def ranges() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in sorted(_supported()):
        if out and c == out[-1][1] + 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def render() -> str:
    rs = ", ".join(f"[0x{a:x}, 0x{b:x}]" for a, b in ranges())
    return f"""// Generated by scripts/gen-lettering-charset.py from the bundled lettering fonts. Do not edit.
/** Code points every lettering face (body regular/bold and SFX) can draw. */
export const LETTERING_RANGES: readonly (readonly [number, number])[] = [{rs}];

export const LETTERING_SUPPORTED_SUMMARY = {SUPPORTED_SUMMARY!r};

/** Distinct characters in `text` that the lettering fonts cannot draw, in order of first use. */
export function unsupportedLetteringChars(text: string): string[] {{
  const seen: string[] = [];
  for (const ch of text) {{
    if (/\\s/.test(ch)) continue;
    const cp = ch.codePointAt(0)!;
    if (!LETTERING_RANGES.some(([a, b]) => cp >= a && cp <= b) && !seen.includes(ch)) seen.push(ch);
  }}
  return seen;
}}

/** The same actionable message the server returns. */
export function unsupportedLetteringMessage(chars: string[]): string {{
  const shown = chars.slice(0, 12).join(", ") + (chars.length > 12 ? "…" : "");
  return `These characters can't be lettered yet: ${{shown}}. ${{LETTERING_SUPPORTED_SUMMARY}} Replace or remove them (for example Ł → L), then try again. Your text is never changed for you.`;
}}
"""


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT} ({len(ranges())} ranges)")
